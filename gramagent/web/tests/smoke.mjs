await page.getByLabel('Review reason').fill('Reviewed synthetic demonstration evidence; approval is for testing only.');
await page.getByRole('checkbox',{name:'I reviewed this exact plan and its evidence.'}).check();
await page.getByRole('button',{name:'Record decision'}).click();
await page.getByText('Decision recorded',{exact:true}).waitFor();
await page.locator('nav a[href="/agents"]').click();
await page.locator('.panel .badge').filter({hasText:'completed'}).waitFor({timeout:30000});
await page.locator('nav a[href="/reports"]').click();
const dl=page.waitForEvent('download');await page.getByRole('button',{name:'Download PDF'}).click();await (await dl).saveAs('.gramagent/sample-report.pdf');
