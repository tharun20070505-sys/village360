import {chromium} from '@playwright/test';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const access=JSON.parse(fs.readFileSync('.gramagent/local-access.json','utf8'));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5174');
await page.getByLabel('Email',{exact:true}).fill(access.email);
await page.getByLabel('Password',{exact:true}).fill(access.password);
await page.getByRole('button',{name:'Sign in',exact:true}).click();
await page.getByRole('heading',{name:'Executive overview',exact:true}).waitFor();
await page.getByRole('link',{name:'Village 360° connection',exact:true}).click();
await page.getByRole('button',{name:'Load demonstration',exact:true}).click();
await page.getByText('SYNTHETIC DEMONSTRATION',{exact:true}).waitFor();
await page.getByRole('link',{name:'Agent activity',exact:true}).click();
await page.getByRole('button',{name:'Run assessment',exact:true}).click();
await page.locator('.panel .badge').filter({hasText:'awaiting_approval'}).waitFor({timeout:60000});
await page.getByRole('link',{name:'Executive overview',exact:true}).click();
await page.screenshot({path:'.gramagent/dashboard.png',fullPage:true});
for(const [path,heading] of [['quality','Data quality'],['diagnosis','Village diagnosis'],['gaps','Development gaps'],['priorities','Problem priorities'],['schemes','Government schemes'],['solutions','Recommended solutions'],['budget','Budget & resources'],['students','Student innovation'],['plan','Development plan'],['map','GIS intelligence'],['reports','Report centre'],['assistant','Village assistant'],['admin','Administration']]){
 await page.locator(`nav a[href="/${path}"]`).click();
 await page.getByRole('heading',{name:heading,exact:true}).first().waitFor();
 assert.equal(await page.locator('[role="alert"]').count(),0,`${path} has an alert`);
}
await page.locator('nav a[href="/scenarios"]').click();
await page.getByLabel('Assumptions and evidence').fill('Synthetic cost of INR 25000 per unit and delivery capacity of 3 per month.');
await page.getByRole('button',{name:'Calculate scenario'}).click();
await page.getByRole('heading',{name:'18 intervention units'}).waitFor();
